import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../../../..')
const abiDir = path.join(root, 'abi')
const outDir = path.join(root, 'frontend/packages/chain/src/contracts')

const SKIP = new Set(['initialize', 'upgradeToAndCall', 'proxiableUUID', 'UPGRADE_INTERFACE_VERSION'])

const CONFIG = [
  { file: 'PlatformAccess.json', exportName: 'platformAccess', className: 'PlatformAccessContract' },
  { file: 'AgentRegistry.json', exportName: 'agentRegistry', className: 'AgentRegistryContract' },
  { file: 'BranchRegistry.json', exportName: 'branchRegistry', className: 'BranchRegistryContract' },
  { file: 'AgentAccess.json', exportName: 'agentAccess', className: 'AgentAccessContract' },
  { file: 'SalesSettings.json', exportName: 'salesSettings', className: 'SalesSettingsContract' },
  { file: 'Ledger.json', exportName: 'ledger', className: 'LedgerContract' },
  { file: 'HistoryIndex.json', exportName: 'historyIndex', className: 'HistoryIndexContract' },
]

function isConstGetter(name) {
  return /^[A-Z][A-Z0-9_]*$/.test(name)
}

function paramList(inputs) {
  if (!inputs?.length) return ''
  return inputs.map((i) => i.name || 'arg').join(', ')
}

function paramTypes(inputs) {
  return inputs ?? []
}

mkdirSync(outDir, { recursive: true })

for (const cfg of CONFIG) {
  const abi = JSON.parse(readFileSync(path.join(abiDir, cfg.file), 'utf8'))
  const fns = abi.filter(
    (item) =>
      item.type === 'function' &&
      item.name &&
      !SKIP.has(item.name) &&
      !isConstGetter(item.name),
  )

  const methods = fns
    .map((fn) => {
      const inputs = paramTypes(fn.inputs)
      const args = inputs.map((i) => i.name || 'arg')
      const feeType = fn.stateMutability === 'view' || fn.stateMutability === 'pure' ? 'read' : 'sc'
      const inputData =
        args.length === 0
          ? '{}'
          : `{ ${args.map((name) => `${name}`).join(', ')} }`
      const signature =
        args.length === 0
          ? `public async ${fn.name}(): Promise<unknown>`
          : `public async ${fn.name}(${inputs.map((i) => `${i.name}: unknown`).join(', ')}): Promise<unknown>`
      return `  ${signature} {
    const result = await this.sendTransaction({
      functionName: ${cfg.exportName}ABI.${fn.name}.name,
      abiData: ${cfg.exportName}ABI.${fn.name},
      inputData: ${inputData},
      feeType: '${feeType}',
    })
    return unwrapValue(result)
  }`
    })
    .join('\n\n')

  const fileBody = `/* generated by scripts/gen-contracts.mjs — chạy lại khi ABI đổi */
import { MtnContract } from '@metanodejs/mtn-contract'
import { ${cfg.exportName}ABI } from '../abi'
import { unwrapValue } from '../normalize'

export class ${cfg.className} extends MtnContract {
  constructor(from: string, to: string) {
    if (!to) throw new Error('Thiếu địa chỉ contract ${cfg.className}')
    super({ from, to })
  }

${methods}
}
`
  const outFile = `${cfg.exportName.replace(/([A-Z])/g, '-$1').toLowerCase().replace(/^-/, '')}.contract.ts`
  const fixedName = {
    platformAccess: 'platform-access.contract.ts',
    agentRegistry: 'agent-registry.contract.ts',
    branchRegistry: 'branch-registry.contract.ts',
    agentAccess: 'agent-access.contract.ts',
    salesSettings: 'sales-settings.contract.ts',
    ledger: 'ledger.contract.ts',
    historyIndex: 'history-index.contract.ts',
  }[cfg.exportName]

  writeFileSync(path.join(outDir, fixedName), fileBody)
  console.log('wrote', fixedName, fns.length, 'methods')
}